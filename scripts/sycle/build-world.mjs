#!/usr/bin/env node
/**
 * Bakes Natural Earth 110m land (public domain, via the `world-atlas` npm
 * package's TopoJSON) into a single SVG path, already projected around YVR,
 * so the arrival board ships no geometry library and no runtime projection
 * of 50 KB of coastline.
 *
 *   curl -sSfL -o /tmp/land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json
 *   node scripts/sycle/build-world.mjs /tmp/land-110m.json
 *
 * The projection is duplicated from `src/domain/sycle/projection.ts` rather
 * than imported, because this is a plain-node script and that is TypeScript.
 * `world.test.ts` checks the two agree.
 */
import { readFileSync, writeFileSync } from "node:fs";

const [, , input] = process.argv;
if (!input) throw new Error("usage: build-world.mjs <land-110m.json>");

const YVR = { latitude: 49.1947, longitude: -123.1792 };
const R = 500;
const RAD = Math.PI / 180;

function project(lat, lon) {
  const φ0 = YVR.latitude * RAD;
  const φ = lat * RAD;
  const Δλ = (lon - YVR.longitude) * RAD;
  const cos =
    Math.sin(φ0) * Math.sin(φ) + Math.cos(φ0) * Math.cos(φ) * Math.cos(Δλ);
  const c = Math.acos(Math.min(1, Math.max(-1, cos)));
  if (c < 1e-9) return { x: 0, y: 0, c };
  const k = c / Math.sin(c);
  const x = k * Math.cos(φ) * Math.sin(Δλ);
  const y =
    k *
    (Math.cos(φ0) * Math.sin(φ) - Math.sin(φ0) * Math.cos(φ) * Math.cos(Δλ));
  return { x: (x * R) / Math.PI, y: (-y * R) / Math.PI, c };
}

const topo = JSON.parse(readFileSync(input, "utf8"));
const { scale, translate } = topo.transform;

const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

const ringOf = (indices) => {
  const out = [];
  for (const i of indices) {
    const arc = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    out.push(...(out.length ? arc.slice(1) : arc));
  }
  return out;
};

// Too close to the antipode and the projection smears a coastline around the
// whole rim. Antarctica is dropped for the same reason and because nobody is
// flying in from it.
const RIM = 168 * RAD;
const MIN_STEP = 1.1;

const parts = [];
const polygons = topo.objects.land.geometries.flatMap((g) =>
  g.type === "Polygon" ? [g.arcs] : g.arcs,
);
for (const polygon of polygons) {
  for (const ring of polygon.map(ringOf)) {
    if (ring.every(([, lat]) => lat < -58)) continue;
    const pts = ring.map(([lon, lat]) => project(lat, lon));
    if (pts.some((p) => p.c > RIM)) continue;
    const kept = [];
    for (const p of pts) {
      const last = kept[kept.length - 1];
      if (!last || Math.hypot(p.x - last.x, p.y - last.y) >= MIN_STEP)
        kept.push(p);
    }
    if (kept.length < 4) continue;
    parts.push(
      "M" +
        kept
          .map(
            (p) => `${Math.round(p.x * 10) / 10},${Math.round(p.y * 10) / 10}`,
          )
          .join("L") +
        "Z",
    );
  }
}

const path = parts.join("");
const out = `// GENERATED by scripts/sycle/build-world.mjs — do not edit by hand.
// Natural Earth 110m land (public domain), projected azimuthal-equidistant
// around YVR into a disc of radius ${R}. Antarctica and anything within 12° of
// the antipode are omitted.
export const WORLD_LAND_PATH =
  ${JSON.stringify(path)};
`;
writeFileSync("src/components/sycle/world.ts", out);
console.log(`${parts.length} rings, ${path.length} bytes`);
