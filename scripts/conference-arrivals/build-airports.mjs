#!/usr/bin/env node
/**
 * Regenerates src/lib/conference-arrivals/airports-data.ts from OurAirports
 * (public domain, https://ourairports.com/data/).
 *
 *   curl -o /tmp/ourairports.csv https://davidmegginson.github.io/ourairports-data/airports.csv
 *   node scripts/conference-arrivals/build-airports.mjs /tmp/ourairports.csv
 *
 * Keeps large and medium airports with scheduled service and both an IATA and
 * an ICAO code: the airports a coworker could be flying out of, and the codes
 * ADS-B route records use. One line per airport, parsed once on the server.
 */
import { readFileSync, writeFileSync } from "node:fs";

const [, , input = "/tmp/ourairports.csv"] = process.argv;
const out = new URL(
  "../../src/lib/conference-arrivals/airports-data.ts",
  import.meta.url,
);

/** RFC 4180-ish: quoted fields, doubled quotes. */
function parse(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (c !== "\r") field += c;
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const [header, ...rows] = parse(readFileSync(input, "utf8"));
const col = (name) => header.indexOf(name);
const clean = (s) => s.replace(/[|\n]/g, " ").trim();

const lines = [];
for (const r of rows) {
  const type = r[col("type")];
  if (type !== "large_airport" && type !== "medium_airport") continue;
  if (r[col("scheduled_service")] !== "yes") continue;
  const iata = r[col("iata_code")]?.trim();
  const icao = (r[col("icao_code")] || r[col("gps_code")] || "").trim();
  if (!/^[A-Z]{3}$/.test(iata ?? "") || !/^[A-Z0-9]{4}$/.test(icao)) continue;
  const lat = Number(r[col("latitude_deg")]).toFixed(4);
  const lon = Number(r[col("longitude_deg")]).toFixed(4);
  lines.push(
    [
      iata,
      icao,
      lat,
      lon,
      type === "large_airport" ? "L" : "M",
      r[col("iso_country")],
      clean(r[col("municipality")] ?? ""),
      clean(r[col("name")]),
    ].join("|"),
  );
}
lines.sort();

writeFileSync(
  out,
  `// prettier-ignore
/**
 * Generated by scripts/conference-arrivals/build-airports.mjs from OurAirports
 * (public domain). Do not edit by hand. ${lines.length} airports.
 *
 * iata|icao|lat|lon|L(arge) or M(edium)|country|city|name
 */
export const AIRPORTS = ${JSON.stringify(lines.join("\n"))};
`,
);
console.log(`wrote ${lines.length} airports to ${out.pathname}`);
